#!/usr/bin/env python3
"""Compare reconstructed Audio RSP COFF bodies and typed data without masks.

This is a source diagnostic, never a complete-DLL success check. Relocations
are materialized only in temporary comparison buffers, using independently
identified original functions, globals, imports and complete literal values.
No executable file is changed or generated by this script.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

from pe_fingerprints import PE32
from verify_gs import COFF, TargetSymbols

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'master/Plugin/audio.dll'
MAP = ROOT / 'analysis/audio-rsp-addresses.json'


def integer(value):
    return int(value, 0) if isinstance(value, str) else value


def sha(data):
    return hashlib.sha256(data).hexdigest()


def read_virtual(image, address, size):
    """Read initialized bytes and the PE loader's zero-filled section tail."""
    for section in image.sections:
        start = image.base + section['rva']
        if start <= address and address + size <= start + section['virtual_size']:
            offset = address - start
            initialized = max(0, min(size, section['raw_size'] - offset))
            return (image.data[section['offset'] + offset:
                               section['offset'] + offset + initialized]
                    + bytes(size - initialized))
    raise ValueError('unmapped original extent: 0x%x + %d' % (address, size))


class Comparison:
    def __init__(self):
        self.image = PE32(TARGET)
        self.document = json.loads(MAP.read_text())
        if self.document['original_sha256'] != sha(self.image.data):
            raise ValueError('original image fingerprint changed')
        self.app = {r['name']: r for r in self.document['symbols']}
        self.symbols = dict(self.app)
        library = json.loads((ROOT / 'analysis/audio-libraries.json').read_text())
        if library['original_sha256'] != sha(self.image.data):
            raise ValueError('library evidence belongs to another image')
        self.symbols.update({r['name']: r for r in library['symbols']})
        imports = TargetSymbols(self.image, rows=[])
        for name, records in imports.by_name.items():
            if len(records) == 1:
                self.symbols[name] = records[0]

    def resolve(self, obj, symbol, addend, function=None):
        name = symbol['name']
        row = self.symbols.get(name)
        if row is None and name.startswith('__imp_') and '@' in name:
            row = self.symbols.get(name.rsplit('@', 1)[0])
        if row:
            return integer(row.get('va', row.get('address'))) + addend, 'identified_symbol'
        if symbol['section'] == -1:
            return symbol['value'] + addend, 'absolute_coff_symbol'
        if function and symbol['section'] == function['section']:
            if function['value'] <= symbol['value'] < function['value'] + function['size']:
                return (function['original_va'] + symbol['value']
                        - function['value'] + addend), 'same_function_label'
        if symbol['section'] > 0 and name.startswith('??_C@'):
            section = obj.sections[symbol['section'] - 1]
            literal = section['data'][symbol['value']:]
            # Compiler string COMDATs contain their complete terminator.
            matches = []
            offset = 0
            while literal:
                offset = self.image.data.find(literal, offset)
                if offset < 0:
                    break
                for original_section in self.image.sections:
                    if (original_section['offset'] <= offset <
                            original_section['offset'] + original_section['raw_size']):
                        matches.append(self.image.base + original_section['rva']
                                       + offset - original_section['offset'])
                offset += 1
            if len(matches) == 1:
                return matches[0] + addend, 'unique_complete_literal'
        return None, 'unresolved'

    def relocated(self, obj, raw, relocations, address, function=None):
        result = bytearray(raw)
        details = []
        for relocation in relocations:
            offset = relocation['offset']
            if relocation['type'] not in (6, 20):
                raise ValueError('unsupported COFF relocation: %s' % relocation)
            addend = struct.unpack_from('<I', result, offset)[0]
            value, basis = self.resolve(obj, relocation['symbol'], addend, function)
            details.append(dict(offset=offset, type=relocation['type'],
                                symbol=relocation['symbol']['name'], addend=addend,
                                target=value, resolution=basis))
            if value is not None:
                if relocation['type'] == 20:
                    value -= address + offset + 4
                struct.pack_into('<I', result, offset, value & 0xffffffff)
        return bytes(result), details

    @staticmethod
    def result(name, original, candidate, relocations, **fields):
        differences = [i for i, (a, b) in enumerate(zip(original, candidate)) if a != b]
        unresolved = sum(r['resolution'] == 'unresolved' for r in relocations)
        return dict(name=name, **fields, original_size=len(original),
                    candidate_size=len(candidate),
                    exact=original == candidate and not unresolved,
                    differing_bytes=len(differences) + abs(len(original) - len(candidate)),
                    first_differences=differences[:32], unresolved=unresolved,
                    original_sha256=sha(original), candidate_materialized_sha256=sha(candidate),
                    relocations=relocations)

    def object(self, path):
        obj = COFF(path)
        functions = []
        for function in obj.functions():
            row = self.app.get(function['name'])
            if not row:
                raise ValueError('unmapped function: ' + function['name'])
            address = integer(row['va'])
            function['original_va'] = address
            candidate, relocations = self.relocated(
                obj, function['data'], function['relocations'], address, function)
            original = read_virtual(self.image, address, integer(row['size']))
            functions.append(self.result(
                row['canonical_name'], original, candidate, relocations,
                symbol=function['name'], va=address,
                body_or_table_extent=row['body_or_table_extent']))
        data = []
        for symbol in obj.symbols:
            row = self.app.get(symbol['name'])
            if (not row or row.get('source') != 'RSPData.c'
                    or symbol['section'] <= 0 or symbol['type'] == 0x20):
                continue
            section = obj.sections[symbol['section'] - 1]
            start, size = symbol['value'], integer(row['size'])
            if start + size > section['size']:
                raise ValueError('typed object exceeds its compiler section')
            relocations = [dict(r, offset=r['offset'] - start)
                           for r in section['relocations']
                           if start <= r['offset'] < start + size]
            address = integer(row['va'])
            candidate, details = self.relocated(
                obj, section['data'][start:start + size], relocations, address)
            original = read_virtual(self.image, address, size)
            data.append(self.result(
                row['canonical_name'], original, candidate, details,
                symbol=symbol['name'], va=address,
                zero_initialized=section['name'] == '.bss'))
        return dict(object=str(path), object_sha256=sha(obj.data),
                    functions=functions, data=data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--object', action='append', required=True, type=Path)
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    comparison = Comparison()
    objects = [comparison.object(p) for p in args.object]
    functions = [r for obj in objects for r in obj['functions']]
    data = [r for obj in objects for r in obj['data']]
    report = dict(original=str(TARGET), original_sha256=sha(comparison.image.data),
                  metadata_sha256=sha(MAP.read_bytes()), diagnostic_only=True,
                  full_dll_byte_exact=False, objects=objects,
                  functions_compared=len(functions),
                  functions_exact=sum(r['exact'] for r in functions),
                  matching_function_bytes=sum(r['original_size'] for r in functions if r['exact']),
                  typed_objects_compared=len(data), typed_objects_exact=sum(r['exact'] for r in data),
                  initialized_data_bytes=sum(r['original_size'] for r in data
                                             if r['exact'] and not r['zero_initialized']),
                  zero_initialized_object_bytes=sum(r['original_size'] for r in data
                                                     if r['exact'] and r['zero_initialized']),
                  unresolved=sum(r['unresolved'] for r in functions + data))
    if args.report:
        args.report.write_text(json.dumps(report, indent=2) + '\n')
    print('%d/%d functions exact; %d matching bytes; %d/%d typed objects exact; %d unresolved relocations' % (
        report['functions_exact'], len(functions), report['matching_function_bytes'],
        report['typed_objects_exact'], len(data), report['unresolved']))
    return 0 if all(r['exact'] for r in functions + data) else 1


if __name__ == '__main__':
    raise SystemExit(main())
